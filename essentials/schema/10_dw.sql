-- ---------------------------------------------------------------------
-- 4. 주문상세팩트 (grain = 주문상세 1행)
-- ---------------------------------------------------------------------
CREATE TABLE dw.fct_ord_line (
  ord_dt_sk     INTEGER      NOT NULL REFERENCES dw.dim_date(date_sk),  -- 주문일자SK
  cust_sk       INTEGER      NOT NULL REFERENCES dw.dim_cust(cust_sk),  -- 주문일자에 유효했던 거래처 버전
  item_sk       INTEGER      NOT NULL REFERENCES dw.dim_item(item_sk),
  emp_sk        INTEGER      NOT NULL REFERENCES dw.dim_emp(emp_sk),    -- 주문을 받은 영업사원 (TB_ORD.EMP_NO)
  ord_no        VARCHAR(14)  NOT NULL,            -- 주문번호 (Degenerate)
  ord_seq       NUMERIC(4)   NOT NULL,            -- 주문순번 (Degenerate)
  ord_stat_cd   VARCHAR(2)   NOT NULL,            -- 주문상태코드 10 접수, 20 확정, 30 출고완료, 90 취소
  ord_qty       NUMERIC(10)  NOT NULL,            -- 주문수량 (가산)
  uprc          NUMERIC(15)  NOT NULL,            -- 단가 (비가산: 합하지 말고 금액÷수량으로 다시 계산)
  ord_amt       NUMERIC(15)  NOT NULL,            -- 주문금액 (가산)
  load_dtm      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  batch_id      VARCHAR(20)  NOT NULL DEFAULT 'INIT',
  PRIMARY KEY (ord_no, ord_seq)
);

INSERT INTO dw.fct_ord_line (ord_dt_sk, cust_sk, item_sk, emp_sk, ord_no, ord_seq, ord_stat_cd, ord_qty, uprc, ord_amt)
SELECT COALESCE(dd.date_sk, -1), COALESCE(dc.cust_sk, -1), COALESCE(di.item_sk, -1), COALESCE(de.emp_sk, -1),
       o.ord_no, d.ord_seq, o.ord_stat_cd, d.ord_qty, d.uprc, d.ord_amt
  FROM erp.tb_ord o
  JOIN erp.tb_ord_dtl d    ON d.ord_no = o.ord_no
  LEFT JOIN dw.dim_date dd ON dd.full_dt = o.ord_dt
  LEFT JOIN dw.dim_cust dc ON dc.cust_no = o.cust_no
                          AND o.ord_dt BETWEEN dc.eff_strt_dt AND dc.eff_end_dt
  LEFT JOIN dw.dim_item di ON di.item_cd = d.item_cd
  LEFT JOIN dw.dim_emp  de ON de.emp_no  = o.emp_no;

-- ---------------------------------------------------------------------
-- 5. 출고상세팩트 (grain = 출고상세 1행 = 주문상세 × 로트)
-- ---------------------------------------------------------------------
CREATE TABLE dw.fct_ship_line (
  ship_dt_sk    INTEGER      NOT NULL REFERENCES dw.dim_date(date_sk),  -- 출고일자SK
  ord_dt_sk     INTEGER      NOT NULL REFERENCES dw.dim_date(date_sk),  -- 주문일자SK (같은 날짜차원의 두 번째 역할)
  cust_sk       INTEGER      NOT NULL REFERENCES dw.dim_cust(cust_sk),  -- 출고일자에 유효했던 거래처 버전
  item_sk       INTEGER      NOT NULL REFERENCES dw.dim_item(item_sk),
  wh_sk         INTEGER      NOT NULL REFERENCES dw.dim_wh(wh_sk),
  lot_sk        INTEGER      NOT NULL REFERENCES dw.dim_lot(lot_sk),
  ship_no       VARCHAR(14)  NOT NULL,            -- 출고번호 (Degenerate)
  ship_seq      NUMERIC(4)   NOT NULL,            -- 출고순번 (Degenerate)
  ord_no        VARCHAR(14)  NOT NULL,            -- 주문번호 (Degenerate, 주문팩트와 드릴 어크로스용)
  ord_seq       NUMERIC(4)   NOT NULL,            -- 주문순번
  ship_qty      NUMERIC(10)  NOT NULL,            -- 출고수량 (가산)
  ship_amt      NUMERIC(15)  NOT NULL,            -- 출고금액 = 출고수량 × 주문상세 단가 (가산, DW 계산값)
  load_dtm      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  batch_id      VARCHAR(20)  NOT NULL DEFAULT 'INIT',
  PRIMARY KEY (ship_no, ship_seq)
);

INSERT INTO dw.fct_ship_line (ship_dt_sk, ord_dt_sk, cust_sk, item_sk, wh_sk, lot_sk,
                              ship_no, ship_seq, ord_no, ord_seq, ship_qty, ship_amt)
SELECT COALESCE(sd.date_sk, -1), COALESCE(od.date_sk, -1), COALESCE(dc.cust_sk, -1),
       COALESCE(di.item_sk, -1), COALESCE(dwh.wh_sk, -1), COALESCE(dl.lot_sk, -1),
       s.ship_no, l.ship_seq, l.ord_no, l.ord_seq, l.ship_qty, l.ship_qty * od2.uprc
  FROM erp.tb_ship s
  JOIN erp.tb_ship_dtl l    ON l.ship_no = s.ship_no
  JOIN erp.tb_ord o         ON o.ord_no  = l.ord_no
  JOIN erp.tb_ord_dtl od2   ON od2.ord_no = l.ord_no AND od2.ord_seq = l.ord_seq
  LEFT JOIN dw.dim_date sd  ON sd.full_dt = s.ship_dt
  LEFT JOIN dw.dim_date od  ON od.full_dt = o.ord_dt
  LEFT JOIN dw.dim_cust dc  ON dc.cust_no = o.cust_no
                           AND s.ship_dt BETWEEN dc.eff_strt_dt AND dc.eff_end_dt
  LEFT JOIN dw.dim_item di  ON di.item_cd = l.item_cd
  LEFT JOIN dw.dim_wh dwh   ON dwh.wh_cd  = s.wh_cd
  LEFT JOIN dw.dim_lot dl   ON dl.lot_no  = l.lot_no;

-- ---------------------------------------------------------------------
-- 6. 일별재고팩트 (주기 스냅샷, grain = 일자 × 창고 × 품목 × 로트)
--    INV_QTY 는 반가산: 창고·품목·로트끼리는 더해도 되지만 날짜끼리는 더하지 않음 (Day 17)
-- ---------------------------------------------------------------------
CREATE TABLE dw.fct_inv_daily (
  inv_dt_sk     INTEGER      NOT NULL REFERENCES dw.dim_date(date_sk),  -- 재고일자SK (마감 기준)
  wh_sk         INTEGER      NOT NULL REFERENCES dw.dim_wh(wh_sk),
  item_sk       INTEGER      NOT NULL REFERENCES dw.dim_item(item_sk),
  lot_sk        INTEGER      NOT NULL REFERENCES dw.dim_lot(lot_sk),
  inv_qty       NUMERIC(12)  NOT NULL,            -- 재고수량 (반가산)
  load_dtm      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  batch_id      VARCHAR(20)  NOT NULL DEFAULT 'INIT',
  PRIMARY KEY (inv_dt_sk, wh_sk, item_sk, lot_sk)
);

INSERT INTO dw.fct_inv_daily (inv_dt_sk, wh_sk, item_sk, lot_sk, inv_qty)
SELECT COALESCE(dd.date_sk, -1), COALESCE(dwh.wh_sk, -1), COALESCE(di.item_sk, -1), COALESCE(dl.lot_sk, -1),
       v.inv_qty
  FROM erp.tb_inv_daily v
  LEFT JOIN dw.dim_date dd  ON dd.full_dt = v.inv_dt
  LEFT JOIN dw.dim_wh dwh   ON dwh.wh_cd  = v.wh_cd
  LEFT JOIN dw.dim_item di  ON di.item_cd = v.item_cd
  LEFT JOIN dw.dim_lot dl   ON dl.lot_no  = v.lot_no;

-- 조회용 인덱스 (팩트 FK). 샘플 규모에서는 의미가 작지만 운영 설계와 모양을 맞춤
CREATE INDEX ix_fct_ord_line_01  ON dw.fct_ord_line  (ord_dt_sk);
CREATE INDEX ix_fct_ord_line_02  ON dw.fct_ord_line  (cust_sk);
CREATE INDEX ix_fct_ship_line_01 ON dw.fct_ship_line (ship_dt_sk);
CREATE INDEX ix_fct_ship_line_02 ON dw.fct_ship_line (ord_no, ord_seq);
CREATE INDEX ix_fct_inv_daily_01 ON dw.fct_inv_daily (item_sk);
