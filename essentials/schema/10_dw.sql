-- =====================================================================
-- 한빛제약그룹 그룹 DW 스타 스키마 (Week 3 Day 15~21, Week 4 가 이 위에 쌓음)
--   실행 순서: 00_base.sql 다음. 운영계(erp) 샘플을 INSERT ... SELECT 로 옮겨 담습니다.
--   다시 실행해도 처음 상태로 돌아갑니다(dw 테이블을 지우고 다시 만듦).
--
--   [차원]                        한 행의 의미                     SCD
--   DW.DIM_DATE      날짜차원     달력 하루 (2025-01-01~2026-12-31)  고정 (DATE_SK = YYYYMMDD)
--   DW.DIM_CUST      거래처차원   거래처 × 담당영업사원 유효기간     Type 2 (TB_CUST_EMP_HIST 기준)
--   DW.DIM_ITEM      품목차원     품목 1개                           Type 1
--   DW.DIM_EMP       사원차원     사원 1명 (부서·본부 펼침)          Type 1
--   DW.DIM_WH        창고차원     창고 1개                           Type 1
--   DW.DIM_LOT       로트차원     로트 1개 (제조일자·유효기한)       Type 0 (바뀌지 않음)
--   [팩트]
--   DW.FCT_ORD_LINE  주문상세팩트 주문상세 1행 (ORD_NO, ORD_SEQ)     트랜잭션 팩트
--   DW.FCT_SHIP_LINE 출고상세팩트 출고상세 1행 (SHIP_NO, SHIP_SEQ)   트랜잭션 팩트 (주문상세 1행이 로트별 여러 행)
--   DW.FCT_INV_DAILY 일별재고팩트 일자 × 창고 × 품목 × 로트          주기 스냅샷 (재고수량은 반가산)
--
--   공통 규칙
--   - 서로게이트 키는 _SK. 차원의 -1 행 = "알 수 없음(Unknown)". 팩트 FK 는 NULL 없이 -1 로 채움.
--   - 날짜 FK 는 DATE_SK (정수 YYYYMMDD). 원천 날짜가 없으면 -1.
--   - SCD2 유효기간은 Day 7 선분이력 규칙과 같음: 종료일 포함, 현재 = 9999-12-31, CURR_YN = 'Y'.
--   - 거래처 SK 는 "사건 일자에 유효했던 버전"으로 찾음 (주문 = 주문일자, 출고 = 출고일자).
--   - 감사 컬럼: LOAD_DTM(적재일시), BATCH_ID(적재 배치). 초기 적재 배치 = 'INIT'.
--   - 업무 키(주문번호 등)를 팩트에 그대로 두는 것은 Degenerate Dimension (Day 18).
-- =====================================================================

DROP TABLE IF EXISTS dw.fct_inv_daily, dw.fct_ship_line, dw.fct_ord_line,
                     dw.dim_lot, dw.dim_wh, dw.dim_emp, dw.dim_item, dw.dim_cust, dw.dim_date CASCADE;

-- ---------------------------------------------------------------------
-- 1. 날짜차원
-- ---------------------------------------------------------------------
CREATE TABLE dw.dim_date (
  date_sk      INTEGER      PRIMARY KEY,          -- 날짜SK = YYYYMMDD, 알 수 없음 = -1
  full_dt      DATE         NOT NULL UNIQUE,      -- 일자 (알 수 없음 행 = 1900-01-01)
  yr           SMALLINT     NOT NULL,             -- 연도
  qtr          SMALLINT     NOT NULL,             -- 분기 1~4
  mm           SMALLINT     NOT NULL,             -- 월 1~12
  yyyymm       CHAR(6)      NOT NULL,             -- 연월 '202603'
  dd           SMALLINT     NOT NULL,             -- 일
  wk_day_no    SMALLINT     NOT NULL,             -- 요일번호 1 월 ~ 7 일 (ISO)
  wk_day_nm    VARCHAR(3)   NOT NULL,             -- 요일명 월·화·…·일
  wkend_yn     CHAR(1)      NOT NULL,             -- 주말여부
  mm_end_yn    CHAR(1)      NOT NULL,             -- 월말여부 (재고 월말 스냅샷용)
  hldy_yn      CHAR(1)      NOT NULL DEFAULT 'N', -- 공휴일여부: 그룹 영업일 달력에서 갱신 (샘플은 모두 N)
  load_dtm     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO dw.dim_date (date_sk, full_dt, yr, qtr, mm, yyyymm, dd, wk_day_no, wk_day_nm, wkend_yn, mm_end_yn)
SELECT TO_CHAR(d, 'YYYYMMDD')::INTEGER,
       d,
       EXTRACT(YEAR FROM d), EXTRACT(QUARTER FROM d), EXTRACT(MONTH FROM d),
       TO_CHAR(d, 'YYYYMM'), EXTRACT(DAY FROM d),
       EXTRACT(ISODOW FROM d),
       (ARRAY['월','화','수','목','금','토','일'])[EXTRACT(ISODOW FROM d)::INT],
       CASE WHEN EXTRACT(ISODOW FROM d) IN (6, 7) THEN 'Y' ELSE 'N' END,
       CASE WHEN d = (DATE_TRUNC('month', d) + INTERVAL '1 month - 1 day')::DATE THEN 'Y' ELSE 'N' END
  FROM generate_series(DATE '2025-01-01', DATE '2026-12-31', INTERVAL '1 day') AS g (dt)
 CROSS JOIN LATERAL (SELECT g.dt::DATE AS d) x;

INSERT INTO dw.dim_date (date_sk, full_dt, yr, qtr, mm, yyyymm, dd, wk_day_no, wk_day_nm, wkend_yn, mm_end_yn)
VALUES (-1, DATE '1900-01-01', 1900, 1, 1, '190001', 1, 1, '-', 'N', 'N');

-- ---------------------------------------------------------------------
-- 2. 거래처차원 (SCD Type 2: 담당영업사원이 바뀌면 새 버전)
-- ---------------------------------------------------------------------
CREATE TABLE dw.dim_cust (
  cust_sk      INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 거래처SK
  cust_no      VARCHAR(10)  NOT NULL,             -- 거래처번호 (업무 키, 버전마다 반복)
  cust_nm      VARCHAR(100) NOT NULL,             -- 거래처명
  cust_tp_cd   VARCHAR(2)   NOT NULL,             -- 거래처유형코드
  cust_tp_nm   VARCHAR(20)  NOT NULL,             -- 거래처유형명 병원·약국·도매상
  rgn_cd       VARCHAR(3)   NOT NULL,             -- 지역코드
  rgn_nm       VARCHAR(20)  NOT NULL,             -- 지역명
  emp_no       VARCHAR(10)  NOT NULL,             -- 담당영업사원번호 (Type 2 추적 속성)
  emp_nm       VARCHAR(50)  NOT NULL,             -- 담당영업사원명
  eff_strt_dt  DATE         NOT NULL,             -- 유효시작일자
  eff_end_dt   DATE         NOT NULL DEFAULT DATE '9999-12-31',  -- 유효종료일자 (포함)
  curr_yn      CHAR(1)      NOT NULL DEFAULT 'Y', -- 현재여부
  load_dtm     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  batch_id     VARCHAR(20)  NOT NULL DEFAULT 'INIT',
  UNIQUE (cust_no, eff_strt_dt)
);

INSERT INTO dw.dim_cust (cust_sk, cust_no, cust_nm, cust_tp_cd, cust_tp_nm, rgn_cd, rgn_nm,
                         emp_no, emp_nm, eff_strt_dt, eff_end_dt, curr_yn)
VALUES (-1, '-1', '알 수 없음', '-1', '알 수 없음', '-1', '알 수 없음',
        '-1', '알 수 없음', DATE '1900-01-01', DATE '9999-12-31', 'Y');

INSERT INTO dw.dim_cust (cust_no, cust_nm, cust_tp_cd, cust_tp_nm, rgn_cd, rgn_nm,
                         emp_no, emp_nm, eff_strt_dt, eff_end_dt, curr_yn)
SELECT c.cust_no, c.cust_nm, c.cust_tp_cd,
       CASE c.cust_tp_cd WHEN '01' THEN '병원' WHEN '02' THEN '약국' WHEN '03' THEN '도매상' ELSE '기타' END,
       c.rgn_cd,
       CASE c.rgn_cd WHEN 'SEL' THEN '서울' WHEN 'GGD' THEN '경기' WHEN 'BSN' THEN '부산' ELSE '기타' END,
       COALESCE(h.emp_no, '-1'), COALESCE(e.emp_nm, '알 수 없음'),
       COALESCE(h.aply_strt_dt, DATE '1900-01-01'),
       COALESCE(h.aply_end_dt,  DATE '9999-12-31'),
       CASE WHEN COALESCE(h.aply_end_dt, DATE '9999-12-31') = DATE '9999-12-31' THEN 'Y' ELSE 'N' END
  FROM erp.tb_cust c
  LEFT JOIN erp.tb_cust_emp_hist h ON h.cust_no = c.cust_no
  LEFT JOIN erp.tb_emp e           ON e.emp_no  = h.emp_no
 ORDER BY c.cust_no, h.aply_strt_dt;

-- ---------------------------------------------------------------------
-- 3. 품목·사원·창고·로트 차원
-- ---------------------------------------------------------------------
CREATE TABLE dw.dim_item (
  item_sk       INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 품목SK
  item_cd       VARCHAR(10)  NOT NULL UNIQUE,     -- 품목코드
  item_nm       VARCHAR(100) NOT NULL,            -- 품목명
  item_tp_cd    VARCHAR(2)   NOT NULL,            -- 품목유형코드
  item_tp_nm    VARCHAR(20)  NOT NULL,            -- 품목유형명 완제품·원료·포장재
  unit_cd       VARCHAR(5)   NOT NULL,            -- 단위코드
  shelf_life_mm NUMERIC(3),                       -- 유효기간(개월)
  load_dtm      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  batch_id      VARCHAR(20)  NOT NULL DEFAULT 'INIT'
);
INSERT INTO dw.dim_item (item_sk, item_cd, item_nm, item_tp_cd, item_tp_nm, unit_cd)
VALUES (-1, '-1', '알 수 없음', '-1', '알 수 없음', '-');
INSERT INTO dw.dim_item (item_cd, item_nm, item_tp_cd, item_tp_nm, unit_cd, shelf_life_mm)
SELECT item_cd, item_nm, item_tp_cd,
       CASE item_tp_cd WHEN 'FG' THEN '완제품' WHEN 'RM' THEN '원료' WHEN 'PM' THEN '포장재'
                       WHEN 'SF' THEN '반제품' ELSE '기타' END,
       unit_cd, shelf_life_mm
  FROM erp.tb_item
 ORDER BY item_cd;

CREATE TABLE dw.dim_emp (
