  emp_nm        VARCHAR(50)  NOT NULL,            -- 사원명
  dept_cd       VARCHAR(10)  NOT NULL,            -- 부서코드 (팀)
  dept_nm       VARCHAR(50)  NOT NULL,            -- 부서명
  hq_dept_nm    VARCHAR(50)  NOT NULL,            -- 본부명 (상위부서를 한 단계 펼침)
  co_cd         VARCHAR(4)   NOT NULL,            -- 회사코드
  load_dtm      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  batch_id      VARCHAR(20)  NOT NULL DEFAULT 'INIT'
);
INSERT INTO dw.dim_emp (emp_sk, emp_no, emp_nm, dept_cd, dept_nm, hq_dept_nm, co_cd)
VALUES (-1, '-1', '알 수 없음', '-1', '알 수 없음', '알 수 없음', '-1');
INSERT INTO dw.dim_emp (emp_no, emp_nm, dept_cd, dept_nm, hq_dept_nm, co_cd)
SELECT e.emp_no, e.emp_nm, d.dept_cd, d.dept_nm, COALESCE(p.dept_nm, d.dept_nm), d.co_cd
  FROM erp.tb_emp e
  JOIN erp.tb_dept d      ON d.dept_cd = e.dept_cd
  LEFT JOIN erp.tb_dept p ON p.dept_cd = d.prnt_dept_cd
 ORDER BY e.emp_no;

